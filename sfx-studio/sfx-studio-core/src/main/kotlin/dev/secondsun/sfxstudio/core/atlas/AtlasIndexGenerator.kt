package dev.secondsun.sfxstudio.core.atlas

/**
 * Generates ca65 compatible assembly include (.i) files describing the Texture Atlas.
 */
internal object AtlasIndexGenerator {
    fun generate(
        atlas: TextureAtlas,
        projectName: String = "TEXTURES",
    ): String = generate(atlas, DescriptorTable.buildFromAtlasOrThrow(atlas).entries, projectName)

    fun generate(
        atlas: TextureAtlas,
        descriptors: List<TextureDescriptorInfo>,
        projectName: String = "TEXTURES",
    ): String {
        val sanitizedProject = SourceTexture.sanitizeToIdentifier(projectName).uppercase()
        val guard = "__${sanitizedProject}_I_DEFINED__"

        val sb = StringBuilder()
        sb.appendLine(";; Auto-generated by SuperFX Texture Atlas Packer")
        sb.appendLine(";; Project: $projectName")
        sb.appendLine(";; Atlas: ${atlas.width}x${atlas.height} (${atlas.sizeBytes} bytes, 1 byte per texel)")
        sb.appendLine()
        sb.appendLine(".ifndef ::$guard")
        sb.appendLine("::$guard = 1")
        sb.appendLine()

        sb.appendLine(";; Structure for runtime texture lookup by IsoEngine / SuperFX")
        sb.appendLine(";; Each descriptor entry is 8 bytes (4 16-bit words) matching the TEXTURE_TABLE format:")
        sb.appendLine(".struct texture_descriptor")
        sb.appendLine("    rom_offset      .word ; Base byte offset of texture (0,0) in atlas binary (Y * ATLAS_WIDTH + X)")
        sb.appendLine("    u_mask          .word ; Horizontal coordinate bitmask for fast wrapping: (width - 1)")
        sb.appendLine("    v_mask_shifted  .word ; Pre-shifted vertical coordinate bitmask: (height - 1) << ATLAS_STRIDE_SHIFT")
        sb.appendLine(
            "    v_offset_mask   .word ; Pre-shifted Q10.6 wrap mask: ((height - 1) << ATLAS_STRIDE_SHIFT) | ((1 << ATLAS_STRIDE_SHIFT) - 1)",
        )
        sb.appendLine(".endstruct")
        sb.appendLine()

        sb.appendLine(";; ==============================================================================")
        sb.appendLine(";; Atlas Dimensions & Constants")
        sb.appendLine(";; ==============================================================================")
        sb.appendLine("ATLAS_WIDTH        = ${atlas.width}")
        sb.appendLine("ATLAS_HEIGHT       = ${atlas.height}")
        sb.appendLine("ATLAS_SIZE_BYTES   = ${atlas.sizeBytes}")
        sb.appendLine(";; ATLAS_STRIDE_SHIFT:")
        sb.appendLine(";;   The power-of-two exponent for the atlas width (log2(ATLAS_WIDTH)).")
        sb.appendLine(";;   On the SuperFX RISC coprocessor, multiplying a row coordinate V by the")
        sb.appendLine(";;   atlas width using the hardware multiplier is cycle-expensive. Instead,")
        sb.appendLine(";;   fast bitwise shifts compute the row byte offset in the atlas:")
        sb.appendLine(";;     row_offset = V << ATLAS_STRIDE_SHIFT   (e.g. V << ${atlas.strideShift} for width ${atlas.width})")
        sb.appendLine(";;     texel_offset = row_offset + U")
        sb.appendLine(".ifndef ATLAS_STRIDE_SHIFT")
        sb.appendLine("ATLAS_STRIDE_SHIFT = ${atlas.strideShift}")
        sb.appendLine(".endif")
        sb.appendLine("ATLAS_FRAC_MASK    = (1 << ATLAS_STRIDE_SHIFT) - 1")

        sb.appendLine("TEXTURE_TABLE_ENTRY_COUNT = ${descriptors.size}")
        sb.appendLine("TEXTURE_TABLE_SIZE_BYTES  = ${descriptors.size * 8}")
        sb.appendLine()

        sb.appendLine(";; ==============================================================================")
        sb.appendLine(";; Per-Texture Symbolic Constants")
        sb.appendLine(";; ==============================================================================")
        sb.appendLine(";; Constant meanings:")
        sb.appendLine(";;   TEXTURE_ID_<NAME>          : Sequential 0-based texture index in TEXTURE_TABLE")
        sb.appendLine(";;   TEXTURE_<NAME>_BYTE_OFFSET : Byte offset into TEXTURE_TABLE (ID * 8 bytes/entry)")
        sb.appendLine(";;   TEXTURE_<NAME>_X / _Y      : Top-left coordinate of texture in atlas (in texels)")
        sb.appendLine(";;   TEXTURE_<NAME>_WIDTH / _HT : Individual texture dimensions (powers of 2)")
        sb.appendLine(";;   TEXTURE_<NAME>_OFFSET      : Absolute byte offset of texture (0,0) in atlas binary")
        sb.appendLine(";;   TEXTURE_<NAME>_U_MASK      : U coordinate mask for power-of-two wrapping (WIDTH - 1)")
        sb.appendLine(";;   TEXTURE_<NAME>_V_MASK      : V coordinate mask for power-of-two wrapping (HEIGHT - 1)")
        sb.appendLine(";;   TEXTURE_<NAME>_WIDTH_SHIFT : log2(WIDTH). Bit-shift count to multiply local coordinate")
        sb.appendLine(";;                                V by texture width: local_offset = (V << WIDTH_SHIFT) + U")
        sb.appendLine(";; ==============================================================================")
        sb.appendLine()

        for ((idx, desc) in descriptors.withIndex()) {
            val upperName = SourceTexture.sanitizeToIdentifier(desc.name).uppercase()
            val byteOffset = idx * 8

            sb.appendLine("TEXTURE_ID_$upperName = $idx")
            sb.appendLine("TEXTURE_${upperName}_BYTE_OFFSET = $byteOffset")
            sb.appendLine("TEXTURE_${upperName}_X = ${desc.x}")
            sb.appendLine("TEXTURE_${upperName}_Y = ${desc.y}")
            sb.appendLine("TEXTURE_${upperName}_WIDTH = ${desc.width}")
            sb.appendLine("TEXTURE_${upperName}_HEIGHT = ${desc.height}")
            sb.appendLine("TEXTURE_${upperName}_OFFSET = ${desc.romOffset}")
            sb.appendLine("TEXTURE_${upperName}_U_MASK = ${desc.uMask}")
            sb.appendLine("TEXTURE_${upperName}_V_MASK = ${desc.vMask}")
            sb.appendLine("TEXTURE_${upperName}_WIDTH_SHIFT = ${desc.widthShift} ; log2(${desc.width}): V << ${desc.widthShift}")
            sb.appendLine("TEXTURE_${upperName}_V_MASK_SHIFTED = (${desc.vMask} << ATLAS_STRIDE_SHIFT)")
            sb.appendLine("TEXTURE_${upperName}_V_OFFSET_MASK = ((${desc.vMask} << ATLAS_STRIDE_SHIFT) | ((1 << ATLAS_STRIDE_SHIFT) - 1))")
            sb.appendLine("TEXTURE_${upperName}_U_OFFSET_MASK = ((${desc.uMask} << 8) | \$00FF)")
            sb.appendLine()
        }

        sb.appendLine(";; ==============================================================================")
        sb.appendLine(";; Texture Table for runtime descriptor lookup")
        sb.appendLine(";; Indexed at runtime via: TEXTURE_TABLE + TEXTURE_<NAME>_BYTE_OFFSET")
        sb.appendLine(";; Format per entry: rom_offset, u_mask, v_mask_shifted, v_offset_mask (8 bytes total)")
        sb.appendLine(";; ==============================================================================")
        sb.appendLine(".segment \"GSUDATA\"")
        sb.appendLine(".import textures_binary")
        sb.appendLine(".export TEXTURE_TABLE")
        sb.appendLine("TEXTURE_TABLE:")
        for ((idx, desc) in descriptors.withIndex()) {
            val upperName = SourceTexture.sanitizeToIdentifier(desc.name).uppercase()
            sb.appendLine(
                "    .word .loword(textures_binary + TEXTURE_${upperName}_OFFSET), ${desc.uMask}, (${desc.vMask} << ATLAS_STRIDE_SHIFT), ((${desc.vMask} << ATLAS_STRIDE_SHIFT) | ((1 << ATLAS_STRIDE_SHIFT) - 1)) ; $idx: ${desc.comment}",
            )
        }
        sb.appendLine(".segment \"GSUCODE\"")
        sb.appendLine()

        sb.appendLine(".endif ; $guard")
        return sb.toString()
    }
}
